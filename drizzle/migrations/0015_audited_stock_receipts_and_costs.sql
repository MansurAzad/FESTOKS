CREATE OR REPLACE FUNCTION public.issue_stock(_salesman uuid, _items jsonb)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  it jsonb;
  p record;
  im text;
  n integer;
  remaining integer;
  take_qty integer;
  lot record;
  changed integer;
BEGIN
  IF NOT public.has_role(auth.uid(), 'admin') THEN RAISE EXCEPTION 'Owner only'; END IF;
  IF _items IS NULL OR jsonb_typeof(_items) IS DISTINCT FROM 'array' OR jsonb_array_length(_items) = 0 THEN
    RAISE EXCEPTION 'At least one issue item is required';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.user_roles WHERE user_id = _salesman AND role = 'salesman'
  ) OR NOT public.user_is_active(_salesman) THEN
    RAISE EXCEPTION 'Active salesman not found';
  END IF;

  PERFORM prod.id FROM public.products prod
  WHERE prod.id IN (
    SELECT DISTINCT (line->>'product_id')::uuid
    FROM jsonb_array_elements(_items) AS lines(line)
    WHERE jsonb_typeof(line) = 'object' AND jsonb_typeof(line->'product_id') = 'string'
  )
  ORDER BY prod.id FOR UPDATE;

  FOR it IN SELECT value FROM jsonb_array_elements(_items) LOOP
    IF jsonb_typeof(it) IS DISTINCT FROM 'object' OR jsonb_typeof(it->'product_id') IS DISTINCT FROM 'string' THEN
      RAISE EXCEPTION 'Invalid issue item';
    END IF;
    SELECT * INTO p FROM public.products WHERE id = (it->>'product_id')::uuid;
    IF NOT FOUND THEN RAISE EXCEPTION 'Product not found'; END IF;

    IF p.is_smartphone THEN
      IF jsonb_typeof(it->'imeis') IS DISTINCT FROM 'array' OR jsonb_array_length(it->'imeis') = 0
         OR EXISTS (SELECT 1 FROM jsonb_array_elements(it->'imeis') AS items(value) WHERE jsonb_typeof(value) IS DISTINCT FROM 'string') THEN
        RAISE EXCEPTION 'Smartphone issue requires valid IMEIs';
      END IF;
      FOR im IN SELECT btrim(value) FROM jsonb_array_elements_text(it->'imeis') AS imeis(value) LOOP
        UPDATE public.imei_units SET status = 'with_salesman', salesman_id = _salesman
        WHERE imei = im AND product_id = p.id AND status = 'in_stock' AND receipt_id IS NOT NULL;
        GET DIAGNOSTICS changed = ROW_COUNT;
        IF changed = 0 THEN RAISE EXCEPTION 'IMEI % not available', im; END IF;
        UPDATE public.stock_receipts
        SET quantity_remaining = quantity_remaining - 1
        WHERE id = (SELECT receipt_id FROM public.imei_units WHERE imei = im)
          AND quantity_remaining > 0;
        IF NOT FOUND THEN RAISE EXCEPTION 'IMEI receipt stock is inconsistent'; END IF;
        INSERT INTO public.stock_movements(
          salesman_id, product_id, kind, qty, unit_price, unit_cost, receipt_id, imei
        )
        SELECT _salesman, p.id, 'issue', 1, p.selling_price, r.unit_cost, r.id, im
        FROM public.imei_units u JOIN public.stock_receipts r ON r.id = u.receipt_id
        WHERE u.imei = im;
      END LOOP;
    ELSE
      IF jsonb_typeof(it->'qty') IS DISTINCT FROM 'number' THEN RAISE EXCEPTION 'Invalid product quantity'; END IF;
      n := (it->>'qty')::numeric;
      IF n <= 0 OR n <> trunc(n) OR n > 2147483647 THEN RAISE EXCEPTION 'Quantity must be a positive whole number'; END IF;
      IF p.stock_qty < n THEN RAISE EXCEPTION 'Not enough stock for %', p.name; END IF;
      remaining := n::integer;
      FOR lot IN
        SELECT id, unit_cost, quantity_remaining
        FROM public.stock_receipts
        WHERE product_id = p.id AND quantity_remaining > 0
        ORDER BY received_on, receipt_order
        FOR UPDATE
      LOOP
        EXIT WHEN remaining = 0;
        take_qty := least(remaining, lot.quantity_remaining);
        UPDATE public.stock_receipts SET quantity_remaining = quantity_remaining - take_qty
        WHERE id = lot.id;
        INSERT INTO public.stock_movements(
          salesman_id, product_id, kind, qty, unit_price, unit_cost, receipt_id
        )
        VALUES (_salesman, p.id, 'issue', take_qty, p.selling_price, lot.unit_cost, lot.id);
        remaining := remaining - take_qty;
      END LOOP;
      IF remaining <> 0 THEN RAISE EXCEPTION 'Receipt balances do not cover %', p.name; END IF;
      PERFORM set_config('app.stock_write', 'enabled', true);
      UPDATE public.products SET stock_qty = stock_qty - n::integer WHERE id = p.id;
    END IF;
  END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_sale(_retailer uuid, _items jsonb, _paid numeric)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  it jsonb;
  p record;
  im text;
  n integer;
  remaining integer;
  take_qty integer;
  changed integer;
  sid uuid;
  retailer_salesman uuid;
  lot record;
  imei_receipt uuid;
  imei_cost numeric;
  sale_total numeric := 0;
  price numeric;
BEGIN
  IF _paid IS NULL OR _paid < 0 THEN RAISE EXCEPTION 'Paid amount cannot be negative'; END IF;
  IF _items IS NULL OR jsonb_typeof(_items) IS DISTINCT FROM 'array' OR jsonb_array_length(_items) = 0 THEN
    RAISE EXCEPTION 'At least one sale item is required';
  END IF;

  SELECT salesman_id INTO retailer_salesman
  FROM public.retailers WHERE id = _retailer FOR UPDATE;
  IF NOT FOUND OR retailer_salesman IS DISTINCT FROM auth.uid() THEN RAISE EXCEPTION 'Retailer not yours'; END IF;

  PERFORM prod.id FROM public.products prod
  WHERE prod.id IN (
    SELECT DISTINCT (line->>'product_id')::uuid
    FROM jsonb_array_elements(_items) AS lines(line)
    WHERE jsonb_typeof(line) = 'object' AND jsonb_typeof(line->'product_id') = 'string'
  )
  ORDER BY prod.id FOR UPDATE;

  INSERT INTO public.sales(salesman_id, retailer_id, total, paid)
  VALUES (auth.uid(), _retailer, 0, _paid) RETURNING id INTO sid;

  FOR it IN SELECT value FROM jsonb_array_elements(_items) LOOP
    IF jsonb_typeof(it) IS DISTINCT FROM 'object' OR jsonb_typeof(it->'product_id') IS DISTINCT FROM 'string' THEN
      RAISE EXCEPTION 'Invalid sale item';
    END IF;
    SELECT * INTO p FROM public.products WHERE id = (it->>'product_id')::uuid;
    IF NOT FOUND THEN RAISE EXCEPTION 'Product not found'; END IF;
    price := coalesce((it->>'unit_price')::numeric, p.selling_price);
    IF price < 0 THEN RAISE EXCEPTION 'Unit price cannot be negative'; END IF;

    IF p.is_smartphone THEN
      IF jsonb_typeof(it->'imeis') IS DISTINCT FROM 'array' OR jsonb_array_length(it->'imeis') = 0
         OR EXISTS (SELECT 1 FROM jsonb_array_elements(it->'imeis') AS items(value) WHERE jsonb_typeof(value) IS DISTINCT FROM 'string') THEN
        RAISE EXCEPTION 'Smartphone sale requires valid IMEIs';
      END IF;
      FOR im IN SELECT btrim(value) FROM jsonb_array_elements_text(it->'imeis') AS imeis(value) LOOP
        SELECT receipt_id, r.unit_cost INTO imei_receipt, imei_cost
        FROM public.imei_units u JOIN public.stock_receipts r ON r.id = u.receipt_id
        WHERE u.imei = im AND u.product_id = p.id AND u.status = 'with_salesman'
          AND u.salesman_id = auth.uid()
        FOR UPDATE OF u;
        IF NOT FOUND THEN RAISE EXCEPTION 'IMEI % not with you', im; END IF;
        UPDATE public.imei_units SET status = 'sold', retailer_id = _retailer WHERE imei = im;
        INSERT INTO public.stock_movements(
          salesman_id, product_id, kind, qty, unit_price, unit_cost, receipt_id,
          imei, sale_id, retailer_id
        )
        VALUES (auth.uid(), p.id, 'sale', 1, price, imei_cost, imei_receipt, im, sid, _retailer);
        sale_total := sale_total + price;
      END LOOP;
    ELSE
      IF jsonb_typeof(it->'qty') IS DISTINCT FROM 'number' THEN RAISE EXCEPTION 'Invalid product quantity'; END IF;
      n := (it->>'qty')::numeric;
      IF n <= 0 OR n <> trunc(n) OR n > 2147483647 THEN RAISE EXCEPTION 'Quantity must be a positive whole number'; END IF;
      IF public.holding_qty(auth.uid(), p.id) < n THEN RAISE EXCEPTION 'Not enough % in hand', p.name; END IF;
      remaining := n::integer;
      FOR lot IN
        SELECT r.id, r.unit_cost, r.receipt_order,
               sum(CASE WHEN m.kind = 'issue' THEN m.qty ELSE -m.qty END)::integer AS held
        FROM public.stock_receipts r
        JOIN public.stock_movements m ON m.receipt_id = r.id
        WHERE r.product_id = p.id AND m.salesman_id = auth.uid()
        GROUP BY r.id, r.unit_cost, r.received_on, r.receipt_order
        HAVING sum(CASE WHEN m.kind = 'issue' THEN m.qty ELSE -m.qty END) > 0
        ORDER BY r.received_on, r.receipt_order
      LOOP
        EXIT WHEN remaining = 0;
        take_qty := least(remaining, lot.held);
        INSERT INTO public.stock_movements(
          salesman_id, product_id, kind, qty, unit_price, unit_cost, receipt_id,
          sale_id, retailer_id
        )
        VALUES (auth.uid(), p.id, 'sale', take_qty, price, lot.unit_cost, lot.id, sid, _retailer);
        remaining := remaining - take_qty;
        sale_total := sale_total + price * take_qty;
      END LOOP;
      IF remaining <> 0 THEN RAISE EXCEPTION 'Receipt balances do not cover %', p.name; END IF;
    END IF;
  END LOOP;

  IF _paid > sale_total THEN RAISE EXCEPTION 'Paid more than total'; END IF;
  UPDATE public.sales SET total = sale_total WHERE id = sid;
  RETURN sid;
END;
$$;

CREATE OR REPLACE FUNCTION public.return_stock(_salesman uuid, _items jsonb)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  it jsonb;
  p record;
  im text;
  n integer;
  remaining integer;
  take_qty integer;
  changed integer;
  damaged boolean;
  lot record;
  imei_receipt uuid;
  imei_cost numeric;
BEGIN
  IF NOT (public.has_role(auth.uid(), 'admin') OR _salesman = auth.uid()) THEN RAISE EXCEPTION 'Forbidden'; END IF;
  IF _items IS NULL OR jsonb_typeof(_items) IS DISTINCT FROM 'array' OR jsonb_array_length(_items) = 0 THEN
    RAISE EXCEPTION 'At least one return item is required';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.user_roles WHERE user_id = _salesman AND role = 'salesman'
  ) THEN RAISE EXCEPTION 'Salesman not found'; END IF;

  PERFORM prod.id FROM public.products prod
  WHERE prod.id IN (
    SELECT DISTINCT (line->>'product_id')::uuid
    FROM jsonb_array_elements(_items) AS lines(line)
    WHERE jsonb_typeof(line) = 'object' AND jsonb_typeof(line->'product_id') = 'string'
  )
  ORDER BY prod.id FOR UPDATE;

  FOR it IN SELECT value FROM jsonb_array_elements(_items) LOOP
    IF jsonb_typeof(it) IS DISTINCT FROM 'object' OR jsonb_typeof(it->'product_id') IS DISTINCT FROM 'string' THEN
      RAISE EXCEPTION 'Invalid return item';
    END IF;
    SELECT * INTO p FROM public.products WHERE id = (it->>'product_id')::uuid;
    IF NOT FOUND THEN RAISE EXCEPTION 'Product not found'; END IF;
    damaged := coalesce((it->>'damaged')::boolean, false);

    IF p.is_smartphone THEN
      IF jsonb_typeof(it->'imeis') IS DISTINCT FROM 'array' OR jsonb_array_length(it->'imeis') = 0
         OR EXISTS (SELECT 1 FROM jsonb_array_elements(it->'imeis') AS items(value) WHERE jsonb_typeof(value) IS DISTINCT FROM 'string') THEN
        RAISE EXCEPTION 'Smartphone return requires valid IMEIs';
      END IF;
      FOR im IN SELECT btrim(value) FROM jsonb_array_elements_text(it->'imeis') AS imeis(value) LOOP
        SELECT u.receipt_id, r.unit_cost INTO imei_receipt, imei_cost
        FROM public.imei_units u JOIN public.stock_receipts r ON r.id = u.receipt_id
        WHERE u.imei = im AND u.product_id = p.id AND u.status = 'with_salesman'
          AND u.salesman_id = _salesman
        FOR UPDATE OF u;
        IF NOT FOUND THEN RAISE EXCEPTION 'IMEI % not with this salesman', im; END IF;
        UPDATE public.imei_units
        SET status = CASE WHEN damaged THEN 'damaged'::public.imei_status ELSE 'in_stock'::public.imei_status END,
            salesman_id = NULL
        WHERE imei = im;
        IF NOT damaged THEN
          UPDATE public.stock_receipts SET quantity_remaining = quantity_remaining + 1
          WHERE id = imei_receipt AND quantity_remaining < quantity_received;
          IF NOT FOUND THEN RAISE EXCEPTION 'IMEI receipt stock is inconsistent'; END IF;
        END IF;
        INSERT INTO public.stock_movements(
          salesman_id, product_id, kind, qty, unit_price, unit_cost, receipt_id, imei
        )
        VALUES (
          _salesman, p.id, CASE WHEN damaged THEN 'damage'::public.move_kind ELSE 'return'::public.move_kind END,
          1, p.selling_price, imei_cost, imei_receipt, im
        );
      END LOOP;
    ELSE
      IF jsonb_typeof(it->'qty') IS DISTINCT FROM 'number' THEN RAISE EXCEPTION 'Invalid product quantity'; END IF;
      n := (it->>'qty')::numeric;
      IF n <= 0 OR n <> trunc(n) OR n > 2147483647 THEN RAISE EXCEPTION 'Quantity must be a positive whole number'; END IF;
      IF public.holding_qty(_salesman, p.id) < n THEN RAISE EXCEPTION 'Return more than held for %', p.name; END IF;
      remaining := n::integer;
      FOR lot IN
        SELECT r.id, r.unit_cost,
               sum(CASE WHEN m.kind = 'issue' THEN m.qty ELSE -m.qty END)::integer AS held
        FROM public.stock_receipts r
        JOIN public.stock_movements m ON m.receipt_id = r.id
        WHERE r.product_id = p.id AND m.salesman_id = _salesman
        GROUP BY r.id, r.unit_cost, r.received_on, r.receipt_order
        HAVING sum(CASE WHEN m.kind = 'issue' THEN m.qty ELSE -m.qty END) > 0
        ORDER BY r.received_on DESC, r.receipt_order DESC
      LOOP
        EXIT WHEN remaining = 0;
        take_qty := least(remaining, lot.held);
        INSERT INTO public.stock_movements(
          salesman_id, product_id, kind, qty, unit_price, unit_cost, receipt_id
        )
        VALUES (
          _salesman, p.id, CASE WHEN damaged THEN 'damage'::public.move_kind ELSE 'return'::public.move_kind END,
          take_qty, p.selling_price, lot.unit_cost, lot.id
        );
        IF NOT damaged THEN
          UPDATE public.stock_receipts SET quantity_remaining = quantity_remaining + take_qty
          WHERE id = lot.id AND quantity_remaining + take_qty <= quantity_received;
          IF NOT FOUND THEN RAISE EXCEPTION 'Receipt stock is inconsistent'; END IF;
        END IF;
        remaining := remaining - take_qty;
      END LOOP;
      IF remaining <> 0 THEN RAISE EXCEPTION 'Receipt balances do not cover %', p.name; END IF;
      IF NOT damaged THEN
        PERFORM set_config('app.stock_write', 'enabled', true);
        UPDATE public.products SET stock_qty = stock_qty + n::integer WHERE id = p.id;
      END IF;
    END IF;
  END LOOP;
END;
$$;
