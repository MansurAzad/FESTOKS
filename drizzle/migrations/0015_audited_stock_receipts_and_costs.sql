CREATE OR REPLACE FUNCTION public.receive_stock(
  _product uuid,
  _imeis jsonb,
  _quantity integer,
  _supplier text,
  _purchase_reference text,
  _batch_reference text,
  _unit_cost numeric,
  _received_on date,
  _note text DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  p public.products%ROWTYPE;
  receipt uuid;
  imei text;
  i integer;
  digit integer;
  checksum integer;
  new_stock integer;
BEGIN
  IF NOT public.has_role(auth.uid(), 'admin') THEN RAISE EXCEPTION 'Owner only'; END IF;
  IF _quantity IS NULL OR _quantity <= 0 OR _unit_cost IS NULL OR _unit_cost < 0
     OR _received_on IS NULL OR coalesce(length(btrim(_supplier)), 0) = 0
     OR coalesce(length(btrim(_purchase_reference)), 0) = 0 THEN
    RAISE EXCEPTION 'Supplier, purchase reference, positive quantity, non-negative unit cost, and receiving date are required';
  END IF;

  SELECT * INTO p FROM public.products WHERE id = _product FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Product not found'; END IF;

  IF p.is_smartphone THEN
    IF jsonb_typeof(_imeis) IS DISTINCT FROM 'array'
       OR jsonb_array_length(_imeis) <> _quantity
       OR EXISTS (
         SELECT 1 FROM jsonb_array_elements(_imeis) AS item(value)
         WHERE jsonb_typeof(value) IS DISTINCT FROM 'string'
       ) THEN
      RAISE EXCEPTION 'Smartphone quantity must match the IMEI list';
    END IF;
    IF EXISTS (
      SELECT value FROM jsonb_array_elements_text(_imeis) AS item(value)
      GROUP BY value HAVING count(*) > 1
    ) THEN
      RAISE EXCEPTION 'Duplicate IMEI in receipt';
    END IF;
    FOR imei IN SELECT btrim(value) FROM jsonb_array_elements_text(_imeis) AS item(value) LOOP
      IF imei !~ '^[0-9]{15}$' THEN RAISE EXCEPTION 'IMEI must contain 15 digits'; END IF;
      checksum := 0;
      FOR i IN 1..15 LOOP
        digit := substring(imei FROM i FOR 1)::integer;
        IF i % 2 = 0 THEN
          digit := digit * 2;
          IF digit > 9 THEN digit := digit - 9; END IF;
        END IF;
        checksum := checksum + digit;
      END LOOP;
      IF checksum % 10 <> 0 THEN RAISE EXCEPTION 'IMEI checksum is invalid'; END IF;
    END LOOP;
  ELSIF coalesce(jsonb_typeof(_imeis), 'array') <> 'array'
        OR coalesce(jsonb_array_length(_imeis), 0) <> 0 THEN
    RAISE EXCEPTION 'Button-phone receipt must not include IMEIs';
  END IF;

  INSERT INTO public.stock_receipts(
    product_id, supplier, purchase_reference, batch_reference,
    quantity_received, quantity_remaining, unit_cost, received_on,
    note, created_by
  )
  VALUES (
    _product, btrim(_supplier), nullif(btrim(_purchase_reference), ''),
    nullif(btrim(_batch_reference), ''), _quantity, _quantity, _unit_cost,
    _received_on, nullif(btrim(_note), ''), auth.uid()
  )
  RETURNING id INTO receipt;

  IF p.is_smartphone THEN
    INSERT INTO public.imei_units(product_id, imei, receipt_id, created_at)
    SELECT _product, btrim(value), receipt, _received_on::timestamp AT TIME ZONE 'Asia/Dhaka'
    FROM jsonb_array_elements_text(_imeis) AS item(value);
  ELSE
    new_stock := p.stock_qty + _quantity;
    IF new_stock > 2147483647 THEN RAISE EXCEPTION 'Stock quantity exceeds the supported limit'; END IF;
    PERFORM set_config('app.stock_write', 'enabled', true);
    UPDATE public.products SET stock_qty = new_stock, cost_price = _unit_cost
    WHERE id = _product;
  END IF;
  IF p.is_smartphone THEN
    UPDATE public.products SET cost_price = _unit_cost WHERE id = _product;
  END IF;

  INSERT INTO public.business_audit(actor, action, entity, entity_id, reason, after_data)
  VALUES (
    auth.uid(), 'stock_receive', 'stock_receipts', receipt,
    coalesce(nullif(btrim(_note), ''), 'Stock receipt'),
    jsonb_build_object(
      'product_id', _product, 'supplier', btrim(_supplier),
      'purchase_reference', nullif(btrim(_purchase_reference), ''),
      'batch_reference', nullif(btrim(_batch_reference), ''),
      'quantity', _quantity, 'unit_cost', _unit_cost, 'received_on', _received_on
    )
  );
  RETURN receipt;
END;
$$;
REVOKE ALL ON FUNCTION public.receive_stock(uuid,jsonb,integer,text,text,text,numeric,date,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.receive_stock(uuid,jsonb,integer,text,text,text,numeric,date,text) TO service_role;

