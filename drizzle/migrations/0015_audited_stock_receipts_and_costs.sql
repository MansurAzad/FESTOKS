CREATE OR REPLACE FUNCTION public.create_legacy_opening_stock_receipts()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  p record;
  receipt uuid;
  received_qty integer;
  warehouse_qty integer;
BEGIN
  FOR p IN SELECT * FROM public.products ORDER BY id LOOP
    IF p.is_smartphone THEN
      SELECT count(*)::integer,
             count(*) FILTER (WHERE status = 'in_stock')::integer
      INTO received_qty, warehouse_qty
      FROM public.imei_units
      WHERE product_id = p.id AND receipt_id IS NULL;
    ELSE
      SELECT greatest(
               p.stock_qty + coalesce(sum(qty) FILTER (WHERE kind = 'issue'), 0)
                 - coalesce(sum(qty) FILTER (WHERE kind = 'return'), 0),
               0
             )::integer,
             p.stock_qty
      INTO received_qty, warehouse_qty
      FROM public.stock_movements
      WHERE product_id = p.id AND receipt_id IS NULL;
    END IF;

    IF received_qty > 0 THEN
      INSERT INTO public.stock_receipts(
        product_id, supplier, batch_reference, quantity_received,
        quantity_remaining, unit_cost, received_on, note
      )
      VALUES (
        p.id, 'Opening balance (purchase cost unknown)', 'LEGACY-OPENING',
        received_qty, warehouse_qty, NULL, current_date,
        'Imported from inventory already present before audited purchase receipts'
      )
      RETURNING id INTO receipt;

      UPDATE public.imei_units SET receipt_id = receipt
      WHERE product_id = p.id AND receipt_id IS NULL;
      UPDATE public.stock_movements SET receipt_id = receipt
      WHERE product_id = p.id AND receipt_id IS NULL;
    END IF;
  END LOOP;
END;
$$;
REVOKE ALL ON FUNCTION public.create_legacy_opening_stock_receipts() FROM PUBLIC, anon, authenticated;

